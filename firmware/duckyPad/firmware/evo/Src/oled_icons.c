#define OLED_ICON_COUNT (sizeof(oled_icon_table) / sizeof(oled_icon_table[0]))

const oled_icon_entry_t* oled_find_icon(uint32_t codepoint)
{
    for (size_t i = 0; i < OLED_ICON_COUNT; i++) {
        if (oled_icon_table[i].codepoint == codepoint) {
            return &oled_icon_table[i];
        }
    }
    return NULL;
}

static uint32_t decode_raw_utf8(const char** str_ptr)
{
    const unsigned char* s = (const unsigned char*)(*str_ptr);
    if (*s == 0) return 0;
    uint32_t cp = 0;
    if (s[0] < 0x80) {
        cp = s[0];
        *str_ptr += 1;
    } else if ((s[0] & 0xE0) == 0xC0 && (s[1] & 0xC0) == 0x80) {
        cp = ((uint32_t)(s[0] & 0x1F) << 6) | (uint32_t)(s[1] & 0x3F);
        *str_ptr += 2;
    } else if ((s[0] & 0xF0) == 0xE0 && (s[1] & 0xC0) == 0x80 && (s[2] & 0xC0) == 0x80) {
        cp = ((uint32_t)(s[0] & 0x0F) << 12) | ((uint32_t)(s[1] & 0x3F) << 6) | (uint32_t)(s[2] & 0x3F);
        *str_ptr += 3;
    } else if ((s[0] & 0xF8) == 0xF0 && (s[1] & 0xC0) == 0x80 && (s[2] & 0xC0) == 0x80 && (s[3] & 0xC0) == 0x80) {
        cp = ((uint32_t)(s[0] & 0x07) << 18) | ((uint32_t)(s[1] & 0x3F) << 12) | ((uint32_t)(s[2] & 0x3F) << 6) | (uint32_t)(s[3] & 0x3F);
        *str_ptr += 4;
    } else {
        cp = '?';
        *str_ptr += 1;
    }
    return cp;
}

uint32_t oled_utf8_next_codepoint(const char** str_ptr)
{
    while (**str_ptr != 0) {
        uint32_t cp = decode_raw_utf8(str_ptr);
        if (cp == 0xFE0EU || cp == 0xFE0FU || cp == 0x200DU) {
            continue;
        }
        return cp;
    }
    return 0;
}

uint8_t oled_utf8_glyph_count(const char* str)
{
    if (str == NULL) return 0;
    uint8_t count = 0;
    const char* p = str;
    while (oled_utf8_next_codepoint(&p) != 0) {
        count++;
    }
    return count;
}

void oled_utf8_truncate_glyphs(char* str, uint8_t max_glyphs)
{
    if (str == NULL) return;
    const char* p = str;
    uint8_t count = 0;
    while (*p != 0) {
        const char* prev = p;
        uint32_t cp = decode_raw_utf8(&p);
        if (cp == 0xFE0EU || cp == 0xFE0FU || cp == 0x200DU) {
            continue;
        }
        count++;
        if (count > max_glyphs) {
            str[prev - str] = 0;
            return;
        }
    }
}

void oled_draw_icon_glyph(const oled_icon_entry_t* icon, FontDef font, SSD1306_COLOR color)
{
    if (icon == NULL) return;
    uint8_t cx = 0, cy = 0;
    ssd1306_GetCursor(&cx, &cy);
    for (uint8_t i = 0; i < font.FontHeight; i++) {
        uint8_t b = (i >= 1 && i <= 8) ? icon->glyph6x8[i - 1] : 0;
        for (uint8_t j = 0; j < font.FontWidth; j++) {
            if ((b << j) & 0x80U) {
                ssd1306_DrawPixel(cx + j, cy + i, color);
            } else {
                ssd1306_DrawPixel(cx + j, cy + i, (SSD1306_COLOR)!color);
            }
        }
    }
    ssd1306_SetCursor(cx + font.FontWidth, cy);
}
