def scale_16_to_w_h(rows16, w, h):
    """Area-aware downsampler from 16x16 to w x h 1-bit monochrome bitmap."""
    # Find bounding box of active pixels in 16x16 to preserve visual punch
    min_r, max_r = 16, -1
    min_c, max_c = 16, -1
    for r in range(16):
        for c in range(16):
            if rows16[r][c] == '#':
                min_r = min(min_r, r)
                max_r = max(max_r, r)
                min_c = min(min_c, c)
                max_c = max(max_c, c)
    if max_r < min_r:
        return [0] * h

    src_h = max(1, max_r - min_r + 1)
    src_w = max(1, max_c - min_c + 1)
    # Leave 1px right/bottom spacing for inline fonts if w <= 7
    avail_w = w - 1 if w <= 7 else w
    avail_h = h - 1 if h <= 8 else h

    out_words = []
    for y in range(h):
        if y >= avail_h:
            out_words.append(0)
            continue
        sy0 = min_r + (y * src_h) / avail_h
        sy1 = min_r + ((y + 1) * src_h) / avail_h
        row_bits = 0
        for x in range(avail_w):
            sx0 = min_c + (x * src_w) / avail_w
            sx1 = min_c + ((x + 1) * src_w) / avail_w
            iy0 = int(sy0)
            iy1 = min(15, int(sy1 - 1e-6))
            ix0 = int(sx0)
            ix1 = min(15, int(sx1 - 1e-6))
            hit = False
            for yy in range(iy0, iy1 + 1):
                for xx in range(ix0, ix1 + 1):
                    if rows16[yy][xx] == '#':
                        hit = True
                        break
                if hit:
                    break
            if hit:
                row_bits |= (1 << (15 - x))
        out_words.append(row_bits)
    return out_words


def rows16_to_bytes(rows16):
    """Converts 16 strings of length 16 into 32 bytes (2 bytes per row, MSB first) for ssd1306_DrawBitmap."""
    out = []
    for r in rows16:
        assert len(r) == 16, f"Row length {len(r)} != 16: {r}"
        b0 = 0
        b1 = 0
        for i in range(8):
            if r[i] == '#':
                b0 |= (1 << (7 - i))
            if r[8 + i] == '#':
                b1 |= (1 << (7 - i))
        out.append(b0)
        out.append(b1)
    return out


def words_to_bitmap_bytes(words, w):
    """Converts MSB-aligned 16-bit words into ssd1306_DrawBitmap byte array."""
    byte_width = (w + 7) // 8
    out = []
    for word in words:
        for b in range(byte_width):
            out.append((word >> (8 * (1 - b))) & 0xFF)
    return out


